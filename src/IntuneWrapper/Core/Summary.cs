using System;
using System.IO;
using System.Linq;
using System.Text;

namespace IntuneWrapper.Core
{
    /// <summary>"Copy all" and text export (FR-27, FR-28), in the order of the Intune "Add Win32 app" wizard.</summary>
    public static class Summary
    {
        private const int LabelWidth = 30;

        public static string Format(string appName, string packageFileName, PackageCommands c)
        {
            var sb = new StringBuilder();
            Line(sb, "Application", appName);
            Line(sb, "Package", packageFileName);

            if (c.Items.Count > 0)
            {
                sb.AppendLine();
                sb.AppendLine("[Package contents]");
                foreach (PackageItem item in c.Items)
                    Line(sb, item.Name + (item.IsFolder ? "\\" : ""), item.ActionLabel + (string.IsNullOrWhiteSpace(item.Command) ? "" : ": " + item.Command));
            }

            sb.AppendLine();
            sb.AppendLine("[App information]");
            Line(sb, "Name", c.AppName.Value);
            Line(sb, "Description", c.Description.Value);
            Line(sb, "Publisher", c.Publisher.Value);
            Line(sb, "App version", c.AppVersion.Value);

            sb.AppendLine();
            sb.AppendLine("[Program]");
            Line(sb, "Install command", c.IntuneInstallCommand);
            if (c.UsesInstallScript) Line(sb, "  (install.cmd runs)", c.Install.Value + " + " + c.Items.Count(i => i.Action != PackageItemAction.Include) + " more step(s)");
            Line(sb, "Uninstall command", c.Uninstall.Value);
            Line(sb, "Installation time required (mins)", c.InstallTimeMinutes.ToString());
            Line(sb, "Allow available uninstall", Portal.YesNo(c.AllowAvailableUninstall));
            Line(sb, "Install behavior", c.InstallContext.ToString());
            Line(sb, "Device restart behavior", CommandGenerator.RestartLabel(c.Restart));
            Line(sb, "Return codes", Portal.ReturnCodes + " (Intune defaults)");

            sb.AppendLine();
            sb.AppendLine("[Requirements]");
            Line(sb, "Operating system architecture", Portal.Label(c.Architecture));
            Line(sb, "Minimum operating system", c.MinimumOs);

            sb.AppendLine();
            sb.AppendLine("[Detection rules]");
            Line(sb, "Rules format", "Manually configure detection rules");
            foreach (var field in c.Detection.Fields())
            {
                Line(sb, field.Key, field.Value);
            }
            return sb.ToString().TrimEnd();
        }

        private static void Line(StringBuilder sb, string label, string value)
        {
            string head = label + ":";
            sb.AppendLine((head.Length < LabelWidth ? head.PadRight(LabelWidth) : head + " ") + (value ?? ""));
        }

        public static string FormatExport(string appName, string packageFileName, PackageCommands commands)
        {
            var sb = new StringBuilder();
            sb.AppendLine(Format(appName, packageFileName, commands));
            sb.AppendLine();
            sb.AppendLine("[Confidence]");
            Line(sb, "Install command", commands.Install.Confidence.ToString());
            Line(sb, "Uninstall command", commands.Uninstall.Confidence.ToString());
            Line(sb, "Detection rule", commands.Detection.Confidence.ToString());
            Line(sb, "Architecture", commands.ArchitectureConfidence.ToString());

            var missing = commands.MissingRequired();
            if (missing.Count > 0)
            {
                sb.AppendLine();
                sb.AppendLine("[Still required before uploading]");
                foreach (string m in missing) sb.AppendLine("- " + m);
            }
            if (commands.Notes.Count > 0)
            {
                sb.AppendLine();
                sb.AppendLine("[Notes]");
                foreach (string note in commands.Notes)
                {
                    sb.AppendLine("- " + note);
                }
            }
            sb.AppendLine();
            sb.AppendLine("Generated by Intune Wrapper " + AppInfo.Version + " on " + DateTime.Now.ToString("yyyy-MM-dd HH:mm"));
            return sb.ToString();
        }

        public static string PackageFileName(string installerFileName)
        {
            return Path.GetFileNameWithoutExtension(installerFileName) + ".intunewin";
        }

        public static string ExportFileName(string appName)
        {
            return SanitizeFileName(appName) + "-commands.txt";
        }

        public static string SanitizeFileName(string name)
        {
            if (string.IsNullOrWhiteSpace(name)) return "installer";
            char[] invalid = Path.GetInvalidFileNameChars();
            string clean = new string(name.Select(c => invalid.Contains(c) ? '_' : c).ToArray()).Trim().TrimEnd('.');
            return clean.Length == 0 ? "installer" : clean;
        }
    }
}
